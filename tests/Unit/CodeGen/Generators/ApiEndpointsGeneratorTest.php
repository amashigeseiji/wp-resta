                                'required' => ['id'],
                            ],
                        ],
                    ],
                ],
            ],
        ]));
        $output = $this->generator->generate($parser);

        $this->assertStringContainsString('response: { id: number; name?: string };', $output);
    }

    public function testGenerateResponseInlineObjectWithoutRequiredKeyIsAllOptional(): void
